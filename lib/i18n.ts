export type Locale = "es" | "en";

const DICTS: Record<Locale, Record<StringKey, string>> = { es, en };

export function getStrings(locale: Locale): Record<StringKey, string> {
  return DICTS[locale] ?? DICTS.es;
}

/** Renders a string, replacing `{name}` placeholders with vars. */
export function fmt(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    template,
  );
}
